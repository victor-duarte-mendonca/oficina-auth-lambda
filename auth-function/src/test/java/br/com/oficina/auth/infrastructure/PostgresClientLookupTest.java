package br.com.oficina.auth.infrastructure;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import br.com.oficina.auth.application.AuthenticateByCpf;
import br.com.oficina.auth.application.AuthenticationResult;
import br.com.oficina.auth.application.AuthenticationResult.Granted;
import br.com.oficina.auth.application.AuthenticationResult.Unauthorized;
import br.com.oficina.auth.domain.ClientAccount;
import br.com.oficina.auth.domain.ClientStatus;
import br.com.oficina.auth.domain.Cpf;
import br.com.oficina.auth.infrastructure.PostgresClientLookup.ClientLookupException;
import java.security.KeyPairGenerator;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Clock;
import java.util.Optional;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.postgresql.ds.PGSimpleDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

/**
 * A consulta real contra PostgreSQL, com o schema da aplicação e o papel {@code oficina_auth_ro} criado
 * como na migration V6 (SELECT em 5 colunas de {@code clients}). Prova também o isolamento: o papel não
 * escreve e não lê e-mail nem telefone.
 */
@Testcontainers
class PostgresClientLookupTest {

    private static final String RO_USER = "oficina_auth_ro";
    private static final String RO_PASSWORD = "senha-readonly-de-teste";

    @Container
    private static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    @BeforeAll
    static void createSchemaAndRole() throws Exception {
        try (Connection admin = DriverManager.getConnection(
                 POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
             Statement sql = admin.createStatement()) {
            // Mesmo desenho de V1 + V5 da aplicação (colunas que importam aqui).
            sql.execute("""
                CREATE TABLE clients (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(150) NOT NULL,
                    cpf_cnpj VARCHAR(14) NOT NULL UNIQUE,
                    client_type VARCHAR(2) NOT NULL,
                    email VARCHAR(100),
                    phone VARCHAR(20),
                    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
                )""");
            sql.execute("""
                INSERT INTO clients (name, cpf_cnpj, client_type, email, phone, status) VALUES
                ('Maria Souza', '52998224725', 'PF', 'maria@x.com', '11999990000', 'ACTIVE'),
                ('Joao Bloqueado', '11144477735', 'PF', 'joao@x.com', NULL, 'BLOCKED'),
                ('Ana Inativa', '12345678909', 'PF', NULL, NULL, 'INACTIVE')""");
            sql.execute("CREATE ROLE " + RO_USER + " LOGIN PASSWORD '" + RO_PASSWORD + "'");
            sql.execute("GRANT CONNECT ON DATABASE " + POSTGRES.getDatabaseName() + " TO " + RO_USER);
            sql.execute("GRANT USAGE ON SCHEMA public TO " + RO_USER);
            sql.execute("GRANT SELECT (id, name, cpf_cnpj, client_type, status) ON clients TO " + RO_USER);
        }
    }

    private static PGSimpleDataSource dataSourceAs(String user, String password) {
        PGSimpleDataSource dataSource = new PGSimpleDataSource();
        dataSource.setUrl(POSTGRES.getJdbcUrl());
        dataSource.setUser(user);
        dataSource.setPassword(password);
        return dataSource;
    }

    private static PostgresClientLookup readOnlyLookup() {
        return new PostgresClientLookup(() -> dataSourceAs(RO_USER, RO_PASSWORD));
    }

    // ===== Consulta =====

    @Test
    void findByCpf_shouldReturnTheActiveClient() {
        Optional<ClientAccount> found = readOnlyLookup().findByCpf(Cpf.parse("529.982.247-25"));

        assertThat(found).hasValueSatisfying(client -> {
            assertThat(client.name()).isEqualTo("Maria Souza");
            assertThat(client.status()).isEqualTo(ClientStatus.ACTIVE);
            assertThat(client.id()).isPositive();
        });
    }

    @Test
    void findByCpf_shouldReturnBlockedAndInactiveClientsSoTheUseCaseCanDecide() {
        assertThat(readOnlyLookup().findByCpf(Cpf.parse("111.444.777-35")))
            .hasValueSatisfying(client -> assertThat(client.status()).isEqualTo(ClientStatus.BLOCKED));
        assertThat(readOnlyLookup().findByCpf(Cpf.parse("123.456.789-09")))
            .hasValueSatisfying(client -> assertThat(client.status()).isEqualTo(ClientStatus.INACTIVE));
    }

    @Test
    void findByCpf_shouldReturnEmptyForAnUnknownCpf() {
        assertThat(readOnlyLookup().findByCpf(Cpf.parse("987.654.321-00"))).isEmpty();
    }

    @Test
    void findByCpf_shouldBeSafeAgainstInjectionBecauseTheCpfIsAlwaysDigitsAndParameterized() {
        // O Value Object só admite 11 dígitos: não há como levar SQL até a consulta.
        assertThat(QUERY_USES_PLACEHOLDER).isTrue();
    }

    private static final boolean QUERY_USES_PLACEHOLDER =
        PostgresClientLookup.QUERY.contains("cpf_cnpj = ?") && !PostgresClientLookup.QUERY.contains("'");

    // ===== Papel somente-leitura (acceptance da spec 02 §10) =====

    @Test
    void readOnlyRole_shouldNotBeAbleToInsert() throws Exception {
        try (Connection connection = dataSourceAs(RO_USER, RO_PASSWORD).getConnection();
             Statement sql = connection.createStatement()) {
            assertThatThrownBy(() -> sql.execute(
                "INSERT INTO clients (name, cpf_cnpj, client_type) VALUES ('X', '00000000191', 'PF')"))
                .isInstanceOf(SQLException.class).hasMessageContaining("permission denied");
        }
    }

    @Test
    void readOnlyRole_shouldNotBeAbleToUpdateOrDelete() throws Exception {
        try (Connection connection = dataSourceAs(RO_USER, RO_PASSWORD).getConnection();
             Statement sql = connection.createStatement()) {
            assertThatThrownBy(() -> sql.execute("UPDATE clients SET status = 'ACTIVE'"))
                .isInstanceOf(SQLException.class).hasMessageContaining("permission denied");
            assertThatThrownBy(() -> sql.execute("DELETE FROM clients"))
                .isInstanceOf(SQLException.class).hasMessageContaining("permission denied");
        }
    }

    @Test
    void readOnlyRole_shouldNotReadEmailOrPhone() throws Exception {
        try (Connection connection = dataSourceAs(RO_USER, RO_PASSWORD).getConnection();
             Statement sql = connection.createStatement()) {
            assertThatThrownBy(() -> sql.executeQuery("SELECT email FROM clients"))
                .isInstanceOf(SQLException.class).hasMessageContaining("permission denied");
            assertThatThrownBy(() -> sql.executeQuery("SELECT phone FROM clients"))
                .isInstanceOf(SQLException.class).hasMessageContaining("permission denied");
        }
    }

    // ===== Falha de infraestrutura =====

    @Test
    void findByCpf_shouldSurfaceDatabaseFailuresWithOnlyTheSqlState() {
        PGSimpleDataSource wrongPassword = dataSourceAs(RO_USER, "senha-errada");
        PostgresClientLookup lookup = new PostgresClientLookup(() -> wrongPassword);

        assertThatThrownBy(() -> lookup.findByCpf(Cpf.parse("529.982.247-25")))
            .isInstanceOfSatisfying(ClientLookupException.class, e -> {
                assertThat(e.sqlState()).isNotBlank();
                assertThat(e.getMessage()).contains("SQLState=").doesNotContain("senha-errada")
                    .doesNotContain(POSTGRES.getHost());
            });
    }

    // ===== Ponta a ponta: caso de uso real + banco real + JWT real =====

    @Test
    void endToEnd_activeClientGetsAToken_andBlockedAndUnknownAreDeniedIdentically() throws Exception {
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        var issuer = new JwtTokenIssuer(
            (java.security.interfaces.RSAPrivateKey) generator.generateKeyPair().getPrivate(),
            "oficina-api", 3600, Clock.systemUTC());
        var useCase = new AuthenticateByCpf(readOnlyLookup(), issuer);

        AuthenticationResult active = useCase.execute("529.982.247-25");
        AuthenticationResult blocked = useCase.execute("111.444.777-35");
        AuthenticationResult unknown = useCase.execute("987.654.321-00");

        assertThat(active).isInstanceOfSatisfying(Granted.class,
            granted -> assertThat(granted.token().accessToken()).startsWith("eyJ"));
        assertThat(blocked).isInstanceOf(Unauthorized.class);
        assertThat(unknown).isInstanceOf(Unauthorized.class);
    }
}
